import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { parse } from "yaml";

const projectRoot = process.cwd();
const configPath = resolve(projectRoot, "config/pipeline.config.yaml");
const outputPath = resolve(projectRoot, "src/generated/template-assets.ts");

const rawConfig = await readFile(configPath, "utf8");
const parsed = parse(rawConfig);
const config = assertConfigShape(parsed);

const configDir = dirname(configPath);
const templateFiles = {};
const templateIdSet = new Set();

for (const template of config.templates) {
  if (templateIdSet.has(template.id)) {
    throw new Error(`Duplicate template id: ${template.id}`);
  }
  templateIdSet.add(template.id);

  if (!config.formats[template.format]) {
    throw new Error(`Template ${template.id} references unknown format: ${template.format}`);
  }

  if (!config.template_styles.styles[template.style]) {
    throw new Error(`Template ${template.id} references unknown style: ${template.style}`);
  }

  if (Array.isArray(template.archetypes)) {
    for (const archetype of template.archetypes) {
      if (!config.post_archetypes.archetypes[archetype]) {
        throw new Error(`Template ${template.id} references unknown archetype: ${archetype}`);
      }
    }
  }

  const templatePath = resolve(configDir, template.file);
  const html = await readFile(templatePath, "utf8");
  templateFiles[template.id] = html;

  // Keep this as a stable, project-relative path for docs/debug output.
  template.file = toPosix(relative(projectRoot, templatePath));
}

for (const [formatKey, format] of Object.entries(config.formats)) {
  if (!templateIdSet.has(format.default_template_id)) {
    throw new Error(`Format ${formatKey} points to missing default_template_id: ${format.default_template_id}`);
  }
}

const generated = [
  "// This file is auto-generated by scripts/embed-template-assets.mjs.",
  "// Do not edit manually.",
  "",
  `export const PIPELINE_CONFIG = ${JSON.stringify(config, null, 2)} as const;`,
  "",
  `export const TEMPLATE_FILES = ${JSON.stringify(templateFiles, null, 2)} as const;`,
  "",
  "export type PipelineConfig = typeof PIPELINE_CONFIG;",
  "export type TemplateFileId = keyof typeof TEMPLATE_FILES;",
  ""
].join("\n");

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, "utf8");

console.log(`Generated ${toPosix(relative(projectRoot, outputPath))} from ${toPosix(relative(projectRoot, configPath))}`);

function assertConfigShape(value) {
  if (!value || typeof value !== "object") {
    throw new Error("pipeline.config.yaml must be an object");
  }

  const config = value;
  if (typeof config.schema_version !== "number") {
    throw new Error("pipeline.config.yaml must define numeric schema_version");
  }

  if (!config.brand || typeof config.brand !== "object") {
    throw new Error("pipeline.config.yaml must define brand");
  }

  if (typeof config.brand.default_name !== "string" || typeof config.brand.default_color !== "string") {
    throw new Error("brand.default_name and brand.default_color are required");
  }

  if (!config.generation || typeof config.generation !== "object") {
    throw new Error("pipeline.config.yaml must define generation");
  }

  if (!config.typography || typeof config.typography !== "object") {
    throw new Error("pipeline.config.yaml must define typography");
  }

  if (!config.typography.profiles || typeof config.typography.profiles !== "object") {
    throw new Error("typography.profiles must be a map");
  }

  if (typeof config.typography.default_font_profile !== "string") {
    throw new Error("typography.default_font_profile must be a string");
  }

  if (!config.typography.profiles[config.typography.default_font_profile]) {
    throw new Error(`typography.default_font_profile is unknown: ${config.typography.default_font_profile}`);
  }

  if (!config.theming || typeof config.theming !== "object") {
    throw new Error("pipeline.config.yaml must define theming");
  }

  if (!config.render || typeof config.render !== "object") {
    throw new Error("pipeline.config.yaml must define render");
  }

  if (!config.render.preset_styles || typeof config.render.preset_styles !== "object") {
    throw new Error("render.preset_styles must be a map");
  }

  if (!config.render.control_defaults || typeof config.render.control_defaults !== "object") {
    throw new Error("render.control_defaults must be a map");
  }

  if (!config.render.format_control_defaults || typeof config.render.format_control_defaults !== "object") {
    throw new Error("render.format_control_defaults must be a map");
  }

  if (!config.runtime || typeof config.runtime !== "object") {
    throw new Error("pipeline.config.yaml must define runtime");
  }

  if (!Number.isInteger(config.generation.carousel_required_slides) || config.generation.carousel_required_slides < 1) {
    throw new Error("generation.carousel_required_slides must be a positive integer");
  }

  if (!config.generation.limits || typeof config.generation.limits !== "object") {
    throw new Error("generation.limits must be a map");
  }

  if (!config.generation.fallbacks || typeof config.generation.fallbacks !== "object") {
    throw new Error("generation.fallbacks must be a map");
  }

  if (!config.formats || typeof config.formats !== "object") {
    throw new Error("pipeline.config.yaml must define formats map");
  }

  for (const formatKey of Object.keys(config.formats)) {
    if (!config.render.format_control_defaults[formatKey]) {
      throw new Error(`render.format_control_defaults missing format: ${formatKey}`);
    }
    if (!config.render.caption_width_rules?.[formatKey]) {
      throw new Error(`render.caption_width_rules missing format: ${formatKey}`);
    }
  }

  if (!config.post_archetypes || typeof config.post_archetypes !== "object") {
    throw new Error("pipeline.config.yaml must define post_archetypes");
  }

  if (
    !config.post_archetypes.archetypes ||
    typeof config.post_archetypes.archetypes !== "object" ||
    Object.keys(config.post_archetypes.archetypes).length === 0
  ) {
    throw new Error("post_archetypes.archetypes must be a non-empty map");
  }

  if (typeof config.post_archetypes.default_archetype !== "string") {
    throw new Error("post_archetypes.default_archetype must be a string");
  }

  if (!config.post_archetypes.archetypes[config.post_archetypes.default_archetype]) {
    throw new Error(`post_archetypes.default_archetype is unknown: ${config.post_archetypes.default_archetype}`);
  }

  if (!config.slot_schema || typeof config.slot_schema !== "object") {
    throw new Error("pipeline.config.yaml must define slot_schema");
  }

  if (!config.slot_schema.defaults || typeof config.slot_schema.defaults !== "object") {
    throw new Error("slot_schema.defaults must be a map");
  }

  if (!config.slot_schema.slot_hints || typeof config.slot_schema.slot_hints !== "object") {
    throw new Error("slot_schema.slot_hints must be a map");
  }

  if (!config.template_styles || typeof config.template_styles !== "object") {
    throw new Error("pipeline.config.yaml must define template_styles");
  }

  if (!config.template_styles.styles || typeof config.template_styles.styles !== "object") {
    throw new Error("template_styles.styles must be a map");
  }

  if (typeof config.template_styles.default_style !== "string") {
    throw new Error("template_styles.default_style must be a string");
  }

  if (!config.template_styles.styles[config.template_styles.default_style]) {
    throw new Error(`template_styles.default_style is unknown: ${config.template_styles.default_style}`);
  }

  if (!Array.isArray(config.templates) || config.templates.length === 0) {
    throw new Error("pipeline.config.yaml must define a non-empty templates array");
  }

  for (const entry of config.templates) {
    if (!entry || typeof entry !== "object") {
      throw new Error("template entries must be objects");
    }
    if (typeof entry.id !== "string" || typeof entry.format !== "string" || typeof entry.file !== "string") {
      throw new Error("template entries require id, format, and file string fields");
    }
    if (typeof entry.style !== "string") {
      throw new Error(`template ${entry.id} requires style`);
    }
  }

  return config;
}

function toPosix(input) {
  return input.replaceAll("\\\\", "/");
}
